static void ttak_aria_dl(const uint8_t *in, uint8_t *out)
{
    uint8_t t;

    t = in[3] ^ in[4] ^ in[9] ^ in[14];
    out[0] = in[6] ^ in[8] ^ in[13] ^ t;
    out[5] = in[1] ^ in[10] ^ in[15] ^ t;
    out[11] = in[2] ^ in[7] ^ in[12] ^ t;
    out[14] = in[0] ^ in[5] ^ in[11] ^ t;

    t = in[2] ^ in[5] ^ in[8] ^ in[15];
    out[1] = in[7] ^ in[9] ^ in[12] ^ t;
    out[4] = in[0] ^ in[11] ^ in[14] ^ t;
    out[10] = in[3] ^ in[6] ^ in[13] ^ t;
    out[15] = in[1] ^ in[4] ^ in[10] ^ t;

    t = in[1] ^ in[6] ^ in[11] ^ in[12];
    out[2] = in[4] ^ in[10] ^ in[15] ^ t;
    out[7] = in[3] ^ in[8] ^ in[13] ^ t;
    out[9] = in[0] ^ in[5] ^ in[14] ^ t;
    out[12] = in[2] ^ in[7] ^ in[9] ^ t;

    t = in[0] ^ in[7] ^ in[10] ^ in[13];
    out[3] = in[5] ^ in[11] ^ in[14] ^ t;
    out[6] = in[2] ^ in[9] ^ in[12] ^ t;
    out[8] = in[1] ^ in[4] ^ in[15] ^ t;
    out[13] = in[3] ^ in[6] ^ in[8] ^ t;
}

static void ttak_aria_rotxor(const uint8_t *src, int n, uint8_t *dst)
{
    int q = n / 8;
    int r = n % 8;
    for (int i = 0; i < 16; ++i) {
        dst[(q + i) % 16] ^= (src[i] >> (unsigned)r);
        if (r != 0) {
            dst[(q + i + 1) % 16] ^= (src[i] << (unsigned)(8 - r));
        }
    }
}

static int ttak_aria_enc_key_setup(const uint8_t *mk, uint8_t *rk, int key_bits)
{
    int r = (key_bits + 256) / 32;
    int q = (key_bits - 128) / 64;
    uint8_t t[16];
    uint8_t w1[16];
    uint8_t w2[16];
    uint8_t w3[16];

    for (int i = 0; i < 16; ++i) {
        t[i] = ttak_aria_s[i % 4][ttak_aria_krk[q][i] ^ mk[i]];
    }
    ttak_aria_dl(t, w1);
    if (r == 14) {
        for (int i = 0; i < 8; ++i) w1[i] ^= mk[16 + i];
    } else if (r == 16) {
        for (int i = 0; i < 16; ++i) w1[i] ^= mk[16 + i];
    }

    q = (q == 2) ? 0 : (q + 1);
    for (int i = 0; i < 16; ++i) {
        t[i] = ttak_aria_s[(2 + i) % 4][ttak_aria_krk[q][i] ^ w1[i]];
    }
    ttak_aria_dl(t, w2);
    for (int i = 0; i < 16; ++i) w2[i] ^= mk[i];

    q = (q == 2) ? 0 : (q + 1);
    for (int i = 0; i < 16; ++i) {
        t[i] = ttak_aria_s[i % 4][ttak_aria_krk[q][i] ^ w2[i]];
    }
    ttak_aria_dl(t, w3);
    for (int i = 0; i < 16; ++i) w3[i] ^= w1[i];

    ttak_secure_zero(rk, (size_t)(16 * (r + 1)));

    ttak_aria_rotxor(mk, 0, rk);
    ttak_aria_rotxor(w1, 19, rk);
    ttak_aria_rotxor(w1, 0, rk + 16);
    ttak_aria_rotxor(w2, 19, rk + 16);
    ttak_aria_rotxor(w2, 0, rk + 32);
    ttak_aria_rotxor(w3, 19, rk + 32);
    ttak_aria_rotxor(w3, 0, rk + 48);
    ttak_aria_rotxor(mk, 19, rk + 48);
    ttak_aria_rotxor(mk, 0, rk + 64);
    ttak_aria_rotxor(w1, 31, rk + 64);
    ttak_aria_rotxor(w1, 0, rk + 80);
    ttak_aria_rotxor(w2, 31, rk + 80);
    ttak_aria_rotxor(w2, 0, rk + 96);
    ttak_aria_rotxor(w3, 31, rk + 96);
    ttak_aria_rotxor(w3, 0, rk + 112);
    ttak_aria_rotxor(mk, 31, rk + 112);
    ttak_aria_rotxor(mk, 0, rk + 128);
    ttak_aria_rotxor(w1, 67, rk + 128);
    ttak_aria_rotxor(w1, 0, rk + 144);
    ttak_aria_rotxor(w2, 67, rk + 144);
    ttak_aria_rotxor(w2, 0, rk + 160);
    ttak_aria_rotxor(w3, 67, rk + 160);
    ttak_aria_rotxor(w3, 0, rk + 176);
    ttak_aria_rotxor(mk, 67, rk + 176);
    ttak_aria_rotxor(mk, 0, rk + 192);
    ttak_aria_rotxor(w1, 97, rk + 192);
    if (r > 12) {
        ttak_aria_rotxor(w1, 0, rk + 208);
        ttak_aria_rotxor(w2, 97, rk + 208);
        ttak_aria_rotxor(w2, 0, rk + 224);
        ttak_aria_rotxor(w3, 97, rk + 224);
    }
    if (r > 14) {
        ttak_aria_rotxor(w3, 0, rk + 240);
        ttak_aria_rotxor(mk, 97, rk + 240);
        ttak_aria_rotxor(mk, 0, rk + 256);
        ttak_aria_rotxor(w1, 109, rk + 256);
    }

    ttak_secure_zero(t, sizeof(t));
    ttak_secure_zero(w1, sizeof(w1));
    ttak_secure_zero(w2, sizeof(w2));
    ttak_secure_zero(w3, sizeof(w3));
    return r;
}

static int ttak_aria_dec_key_setup(const uint8_t *mk, uint8_t *rk, int key_bits)
{
    uint8_t t[16];
    int r = ttak_aria_enc_key_setup(mk, rk, key_bits);

    for (int j = 0; j < 16; ++j) {
        t[j] = rk[j];
        rk[j] = rk[16 * r + j];
        rk[16 * r + j] = t[j];
    }
    for (int i = 1; i <= r / 2; ++i) {
        ttak_aria_dl(rk + i * 16, t);
        ttak_aria_dl(rk + (r - i) * 16, rk + i * 16);
        for (int j = 0; j < 16; ++j) {
            rk[(r - i) * 16 + j] = t[j];
        }
    }
    ttak_secure_zero(t, sizeof(t));
    return r;
}

static void ttak_aria_crypt(const uint8_t *in, int r, const uint8_t *rk, uint8_t *out)
{
    uint8_t t[16];

    for (int j = 0; j < 16; ++j) out[j] = in[j];
    for (int i = 0; i < r / 2; ++i) {
        for (int j = 0; j < 16; ++j) t[j] = ttak_aria_s[j % 4][rk[j] ^ out[j]];
        ttak_aria_dl(t, out);
        rk += 16;
        for (int j = 0; j < 16; ++j) t[j] = ttak_aria_s[(2 + j) % 4][rk[j] ^ out[j]];
        ttak_aria_dl(t, out);
        rk += 16;
    }
    ttak_aria_dl(out, t);
    for (int j = 0; j < 16; ++j) out[j] = rk[j] ^ t[j];
    ttak_secure_zero(t, sizeof(t));
}

size_t ttak_aria_schedule_init(ttak_aria_schedule_t *sched,
                               const uint8_t *key,
                               size_t key_len) {
    if (!sched || !key) {
        return 0;
    }

    int key_bits;
    switch (key_len) {
        case 16:
            key_bits = 128;
            break;
        case 24:
            key_bits = 192;
            break;
        case 32:
            key_bits = 256;
            break;
        default:
            return 0;
    }

    ttak_secure_zero(sched, sizeof(*sched));
    sched->rounds = (size_t)ttak_aria_enc_key_setup(key, sched->enc_keys, key_bits);
    (void)ttak_aria_dec_key_setup(key, sched->dec_keys, key_bits);
    return sched->rounds;
}

void ttak_aria_encrypt_block(uint8_t *out,
                             const uint8_t *in,
                             const ttak_aria_schedule_t *sched) {
    if (!out || !in || !sched || sched->rounds == 0) {
        return;
    }
    ttak_aria_crypt(in, (int)sched->rounds, sched->enc_keys, out);
}

void ttak_aria_decrypt_block(uint8_t *out,
                             const uint8_t *in,
                             const ttak_aria_schedule_t *sched) {
    if (!out || !in || !sched || sched->rounds == 0) {
        return;
    }
    ttak_aria_crypt(in, (int)sched->rounds, sched->dec_keys, out);
}

void ttak_aria_schedule_wipe(ttak_aria_schedule_t *sched) {
    if (!sched) {
        return;
    }
    ttak_secure_zero(sched, sizeof(*sched));
}
