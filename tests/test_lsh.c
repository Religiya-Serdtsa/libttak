static int test_other_variants_run(void) {
    const uint8_t msg[] = {0x00, 0x01, 0x02, 0x03};
    uint8_t hash224[TTAK_LSH224_DIGEST_SIZE];
    uint8_t hash384[TTAK_LSH384_DIGEST_SIZE];
    ttak_lsh_ctx_t ctx;

    if (ttak_lsh_init(&ctx, TTAK_LSH_224) != 0) {
        printf("FAIL: LSH-224 init\n");
        return 1;
    }
    ttak_lsh_update(&ctx, msg, sizeof(msg));
    ttak_lsh_final(&ctx, hash224);

    if (ttak_lsh_init(&ctx, TTAK_LSH_384) != 0) {
        printf("FAIL: LSH-384 init\n");
        return 1;
    }
    ttak_lsh_update(&ctx, msg, sizeof(msg));
    ttak_lsh_final(&ctx, hash384);

    return 0;
}

int main(void) {
    init_test_data();

    int failures = 0;
    failures += test_lsh256_vectors();
    failures += test_lsh512_vectors();
    failures += test_other_variants_run();

    if (failures == 0) {
        printf("LSH tests passed.\n");
    }
    return failures;
}
