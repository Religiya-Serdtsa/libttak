static int test_lsh256_vectors(void) {
    int failures = 0;
    for (size_t i = 0; i < sizeof(lsh256_steps) / sizeof(lsh256_steps[0]); ++i) {
        ttak_lsh_ctx_t ctx;
        uint8_t hash[TTAK_LSH256_DIGEST_SIZE];
        if (ttak_lsh_init(&ctx, TTAK_LSH_256) != 0) {
            printf("FAIL: LSH-256 init\n");
            return 1;
        }
        ttak_lsh_update_bits(&ctx, test_data, lsh256_steps[i]);
        ttak_lsh_final(&ctx, hash);
        if (memcmp(hash, lsh256_expected[i], TTAK_LSH256_DIGEST_SIZE) != 0) {
            printf("FAIL: LSH-256 vector %zu (len=%zu)\n", i, lsh256_steps[i]);
            failures++;
        }
    }
    return failures;
}

